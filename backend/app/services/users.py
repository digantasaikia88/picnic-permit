"""Officer accounts: create, rename, deactivate, reset password, bulk create.

Passwords are generated by the portal, shown or downloaded once, and stored
only as a hash. Every generated password must be changed at the next login.
"""

from dataclasses import dataclass
from datetime import UTC, datetime

from sqlalchemy import func, or_, select
from sqlalchemy.orm import Session

from app.core import security
from app.core.errors import ConflictError, DomainError, NotFoundError
from app.models import District, DtoOffice, PoliceStation, Role, User
from app.services import audit, auth, masters
from app.services import settings as app_settings
from app.services.user_ids import is_valid_user_id, normalise_user_id, suggest_user_id

BULK_COLUMNS = ["Role", "District ID", "Police Station Name"]

# Role names accepted in the bulk upload file (compared without case or spaces).
_ROLE_NAMES = {
    "dto": Role.DTO,
    "dcoffice": Role.DC_OFFICE,
    "dc": Role.DC_OFFICE,
    "policestation": Role.POLICE_STATION,
    "ps": Role.POLICE_STATION,
    "viewer": Role.VIEWER,
    "stateadmin": Role.STATE_ADMIN,
    "admin": Role.STATE_ADMIN,
}

ROLE_LABELS = {
    Role.STATE_ADMIN: "State Admin",
    Role.DTO: "DTO",
    Role.POLICE_STATION: "Police Station",
    Role.DC_OFFICE: "DC Office",
    Role.VIEWER: "Viewer",
}


@dataclass(frozen=True)
class OfficeLink:
    district: District | None = None
    police_station: PoliceStation | None = None
    dto_office: DtoOffice | None = None


def get_user(db: Session, user_pk: int) -> User:
    user = db.get(User, user_pk)
    if user is None:
        raise NotFoundError("User not found.")
    return user


def status_of(user: User) -> str:
    now = datetime.now(UTC)
    if not user.is_active:
        return "INACTIVE"
    if user.locked_until and user.locked_until > now:
        return "LOCKED"
    if user.password_hash is None:
        return "NO_PASSWORD"
    if user.must_change_password:
        return "MUST_CHANGE_PASSWORD"
    return "ACTIVE"


def list_users(
    db: Session,
    *,
    role: Role | None = None,
    district_id: int | None = None,
    search: str | None = None,
    page: int = 1,
    page_size: int = 50,
) -> tuple[list[User], int]:
    statement = select(User)
    if role is not None:
        statement = statement.where(User.role == role)
    if district_id is not None:
        statement = (
            statement.outerjoin(PoliceStation, User.police_station_id == PoliceStation.id)
            .outerjoin(DtoOffice, User.dto_office_id == DtoOffice.id)
            .where(
                or_(
                    User.district_id == district_id,
                    PoliceStation.district_id == district_id,
                    DtoOffice.district_id == district_id,
                )
            )
        )
    if search:
        statement = statement.where(User.user_id.contains(search.strip().lower(), autoescape=True))

    total = db.scalar(select(func.count()).select_from(statement.subquery())) or 0
    rows = db.scalars(
        statement.order_by(User.user_id).offset((page - 1) * page_size).limit(page_size)
    )
    return list(rows), total


def resolve_office(
    db: Session,
    role: Role,
    *,
    district_id: int | None,
    police_station_id: int | None,
    dto_office_id: int | None,
) -> OfficeLink:
    """Check that the office chosen fits the role, and load it."""
    if role == Role.DTO:
        if dto_office_id is None:
            raise DomainError("Choose the DTO office.")
        return OfficeLink(dto_office=masters.get_dto_office(db, dto_office_id))
    if role == Role.POLICE_STATION:
        if police_station_id is None:
            raise DomainError("Choose the police station.")
        return OfficeLink(police_station=masters.get_police_station(db, police_station_id))
    if role == Role.DC_OFFICE:
        if district_id is None:
            raise DomainError("Choose the district.")
        return OfficeLink(district=masters.get_district(db, district_id))
    if role == Role.VIEWER and district_id is not None:
        return OfficeLink(district=masters.get_district(db, district_id))
    return OfficeLink()


def suggest_for(db: Session, role: Role, link: OfficeLink) -> str:
    return suggest_user_id(
        db,
        role,
        district=link.district,
        police_station=link.police_station,
        dto_office=link.dto_office,
    )


def _new_password(db: Session) -> str:
    return security.generate_password(
        app_settings.get_int(db, app_settings.GENERATED_PASSWORD_LENGTH)
    )


def _issue_password(db: Session, user: User) -> str:
    password = _new_password(db)
    user.password_hash = security.hash_password(password)
    user.must_change_password = True
    user.failed_attempts = 0
    user.locked_until = None
    user.password_issued_at = datetime.now(UTC)
    return password


def create_user(
    db: Session,
    actor: User | None,
    *,
    role: Role,
    link: OfficeLink,
    user_id: str | None = None,
    office_name: str | None = None,
    with_password: bool = True,
    system_label: str = audit.SYSTEM_CLI,
) -> tuple[User, str | None]:
    """Create one officer account. Returns (user, generated password or None)."""
    if user_id:
        user_id = normalise_user_id(user_id)
        if not is_valid_user_id(user_id):
            raise DomainError(
                "A user ID may contain only lowercase letters, digits and dots, "
                "for example dto.tinsukia."
            )
    else:
        user_id = suggest_for(db, role, link)

    if db.scalar(select(User.id).where(User.user_id == user_id)) is not None:
        raise ConflictError(f"The user ID {user_id} is already in use.")

    user = User(
        user_id=user_id,
        role=role,
        office_name=" ".join(office_name.split()) if office_name and office_name.strip() else None,
        district_id=link.district.id if link.district else None,
        police_station_id=link.police_station.id if link.police_station else None,
        dto_office_id=link.dto_office.id if link.dto_office else None,
        must_change_password=True,
    )
    password = _issue_password(db, user) if with_password else None
    db.add(user)
    db.flush()
    audit.record(
        db,
        actor=actor,
        system_label=system_label,
        action="user.create",
        entity_type="user",
        entity_id=user.id,
        entity_label=user.user_id,
        new={
            "user_id": user.user_id,
            "role": user.role.value,
            "district_id": user.district_id,
            "police_station_id": user.police_station_id,
            "dto_office_id": user.dto_office_id,
            "password_issued": with_password,
        },
    )
    return user, password


def update_user(
    db: Session,
    actor: User,
    user_pk: int,
    *,
    user_id: str | None = None,
    is_active: bool | None = None,
    office_name: str | None = None,
) -> User:
    user = get_user(db, user_pk)
    before = {"user_id": user.user_id, "is_active": user.is_active, "office_name": user.office_name}

    if user_id is not None:
        new_id = normalise_user_id(user_id)
        if not is_valid_user_id(new_id):
            raise DomainError("A user ID may contain only lowercase letters, digits and dots.")
        if new_id != user.user_id:
            if db.scalar(select(User.id).where(User.user_id == new_id)) is not None:
                raise ConflictError(f"The user ID {new_id} is already in use.")
            user.user_id = new_id

    if office_name is not None:
        user.office_name = " ".join(office_name.split()) or None

    if is_active is not None and is_active != user.is_active:
        if not is_active:
            if user.id == actor.id:
                raise DomainError("You cannot deactivate your own account.")
            if user.role == Role.STATE_ADMIN and _active_admin_count(db) <= 1:
                raise DomainError("The last active State Admin cannot be deactivated.")
            auth.revoke_sessions(db, user)
        user.is_active = is_active

    old, new = audit.changed_fields(
        before,
        {"user_id": user.user_id, "is_active": user.is_active, "office_name": user.office_name},
    )
    if new:
        audit.record(
            db,
            actor=actor,
            action="user.update",
            entity_type="user",
            entity_id=user.id,
            entity_label=user.user_id,
            old=old,
            new=new,
        )
    return user


def _active_admin_count(db: Session) -> int:
    return (
        db.scalar(
            select(func.count())
            .select_from(User)
            .where(User.role == Role.STATE_ADMIN, User.is_active)
        )
        or 0
    )


def reset_password(db: Session, actor: User | None, user_pk: int) -> tuple[User, str]:
    """Generate a new password, end the user's sessions and force a change at next login."""
    user = get_user(db, user_pk)
    password = _issue_password(db, user)
    auth.revoke_sessions(db, user)
    audit.record(
        db,
        actor=actor,
        action="user.password_reset",
        entity_type="user",
        entity_id=user.id,
        entity_label=user.user_id,
    )
    return user, password


def count_pending_first_passwords(db: Session) -> dict[str, int]:
    never_issued = (
        db.scalar(
            select(func.count())
            .select_from(User)
            .where(User.is_active, User.password_hash.is_(None))
        )
        or 0
    )
    issued_never_logged_in = (
        db.scalar(
            select(func.count())
            .select_from(User)
            .where(User.is_active, User.password_hash.is_not(None), User.last_login_at.is_(None))
        )
        or 0
    )
    return {"never_issued": never_issued, "issued_never_logged_in": issued_never_logged_in}


def generate_first_passwords(
    db: Session, actor: User, *, include_never_logged_in: bool = False
) -> list[tuple[User, str]]:
    """Issue passwords to accounts that have none yet.

    With `include_never_logged_in`, accounts that were issued a password but
    have never logged in get a new one too (for a lost download).
    The admin's own account is never touched.
    """
    condition = User.password_hash.is_(None)
    if include_never_logged_in:
        condition = or_(condition, User.last_login_at.is_(None))
    users = list(
        db.scalars(
            select(User)
            .where(User.is_active, User.id != actor.id, condition)
            .order_by(User.user_id)
        )
    )
    issued = [(user, _issue_password(db, user)) for user in users]
    if issued:
        audit.record(
            db,
            actor=actor,
            action="user.first_passwords_generated",
            entity_type="user",
            new={
                "accounts": len(issued),
                "include_never_logged_in": include_never_logged_in,
            },
        )
    return issued


def _parse_role(raw: str) -> Role | None:
    return _ROLE_NAMES.get("".join(raw.lower().split()).replace("_", ""))


def bulk_create(db: Session, actor: User, rows: list[dict[str, str]]) -> list[tuple[User, str]]:
    """Create users from an uploaded list. All or nothing.

    Columns: Role, District ID, Police Station Name (for police stations),
    and optionally User ID to override the generated one.
    """
    errors: list[str] = []
    plans: list[tuple[int, Role, OfficeLink, str | None]] = []

    for row_number, row in enumerate(rows, start=2):
        role = _parse_role(row.get("Role", ""))
        if role is None:
            errors.append(
                f"Row {row_number}: Role must be DTO, DC Office, Police Station, "
                "Viewer or State Admin."
            )
            continue

        raw_district = row.get("District ID", "")
        district: District | None = None
        if raw_district:
            try:
                district = db.scalar(select(District).where(District.code == int(raw_district)))
            except ValueError:
                district = None
            if district is None:
                errors.append(f"Row {row_number}: District ID '{raw_district}' is not known.")
                continue
        elif role in (Role.DTO, Role.DC_OFFICE, Role.POLICE_STATION):
            errors.append(f"Row {row_number}: District ID is needed for this role.")
            continue

        link = OfficeLink()
        if role == Role.DTO:
            office = db.scalar(
                select(DtoOffice).where(DtoOffice.district_id == district.id).order_by(DtoOffice.id)
            )
            if office is None:
                errors.append(f"Row {row_number}: {district.name} has no DTO office in the master.")
                continue
            link = OfficeLink(dto_office=office)
        elif role == Role.POLICE_STATION:
            name = " ".join(row.get("Police Station Name", "").split())
            station = db.scalar(
                select(PoliceStation).where(
                    PoliceStation.district_id == district.id,
                    func.lower(PoliceStation.name) == name.lower(),
                )
            )
            if station is None:
                errors.append(
                    f"Row {row_number}: police station '{name}' is not in {district.name}."
                )
                continue
            link = OfficeLink(police_station=station)
        elif role in (Role.DC_OFFICE, Role.VIEWER) and district is not None:
            link = OfficeLink(district=district)

        plans.append((row_number, role, link, row.get("User ID") or None))

    if errors:
        raise DomainError(
            f"No users were created. The file has {len(errors)} problem(s).", errors=errors[:100]
        )

    created: list[tuple[User, str]] = []
    for row_number, role, link, user_id in plans:
        try:
            user, password = create_user(db, actor, role=role, link=link, user_id=user_id)
        except DomainError as exc:
            raise DomainError(
                "No users were created. The file has 1 problem(s).",
                errors=[f"Row {row_number}: {exc.message}"],
            ) from exc
        created.append((user, password or ""))
    return created


def credentials_rows(issued: list[tuple[User, str]]) -> list[list[object]]:
    """Rows of the Excel download that carries user IDs and passwords."""
    rows: list[list[object]] = []
    for user, password in issued:
        district = user.jurisdiction_district
        rows.append(
            [
                user.user_id,
                password,
                ROLE_LABELS[user.role],
                user.office_label,
                district.name if district else "",
            ]
        )
    return rows


